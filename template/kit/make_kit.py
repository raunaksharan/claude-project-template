"""Generate Public API sections and starter branches from reference code (optional tool).

    python3 kit/make_kit.py api 03        # print the Public API section of milestone 3's SPEC.md
    python3 kit/make_kit.py spec 03       # refresh that section inside SPEC.md
    python3 kit/make_kit.py spec all
    python3 kit/make_kit.py build 03      # (re)create branch milestone-03-start
    python3 kit/make_kit.py export 01 DIR # the whole start tree, without git history

Configured by kit/milestones.json. A start branch is the milestone's reference code
(`base`) with every module in its `build` list replaced by a file holding only its module
docstring and a pointer to SPEC.md. Everything else (types, data, wiring, tests) is the
seed and stays as it is. Run it from the repo root on a clean working tree.
"""

from __future__ import annotations

import ast
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
_ALL = json.loads((ROOT / "kit/milestones.json").read_text())
CFG = _ALL["_config"]
LESSONS = {k: v for k, v in _ALL.items() if not k.startswith("_")}
PACKAGE = CFG["package"]
PREFIX = CFG.get("branch_prefix", "milestone")
MDIR = CFG.get("milestones_dir", "milestones")
MARK_START = "<!-- api:start (generated by kit/make_kit.py) -->"
MARK_END = "<!-- api:end -->"


def git(*args: str, cwd: Path = ROOT) -> str:
    return subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True,
                          text=True).stdout


def show(ref: str, path: str) -> str:
    return git("show", f"{ref}:{path}")


def module_name(path: str) -> str:
    return path.removeprefix("src/").removesuffix(".py").replace("/", ".")


# -- API extraction -------------------------------------------------------------------

def _sig(fn: ast.FunctionDef) -> str:
    a = ast.unparse(fn.args)
    ret = f" -> {ast.unparse(fn.returns)}" if fn.returns else ""
    return f"{fn.name}({a}){ret}"


def _doc(node: ast.AST) -> str:
    d = ast.get_docstring(node, clean=True)
    return d or ""


def _quote(text: str, indent: str = "") -> list[str]:
    return [f"{indent}> {line}".rstrip() for line in text.splitlines()]


def api_for(ref: str, path: str, importers: dict[str, set[str]]) -> str:
    tree = ast.parse(show(ref, path))
    mod = module_name(path)
    out = [f"### `{path}`", ""]
    used = importers.get(mod, set())
    if used:
        out += ["Imported elsewhere (keep these names exactly): "
                + ", ".join(f"`{n}`" for n in sorted(used)), ""]
    deps = sorted({n.module for n in tree.body if isinstance(n, ast.ImportFrom)
                   and n.module and n.module.startswith(PACKAGE)})
    if deps:
        out += ["Builds on: " + ", ".join(f"`{d}`" for d in deps), ""]
    for node in tree.body:
        if isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            names = [t.id for t in targets if isinstance(t, ast.Name)]
            if not names or all(n.startswith("_") for n in names):
                continue
            value = ast.unparse(node.value) if node.value is not None else ""
            if len(value) > 90:
                value = value[:87] + "…"
            out.append(f"- constant `{names[0]} = {value}`")
        elif isinstance(node, ast.FunctionDef) and not node.name.startswith("_"):
            out += [f"- function `{_sig(node)}`"]
            out += _quote(_doc(node), "  ") if _doc(node) else []
        elif isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
            bases = ", ".join(ast.unparse(b) for b in node.bases)
            out.append(f"- class `{node.name}({bases})`" if bases else f"- class `{node.name}`")
            if _doc(node):
                out += _quote(_doc(node), "  ")
            for item in node.body:
                if isinstance(item, ast.AnnAssign) and isinstance(item.target, ast.Name):
                    default = f" = {ast.unparse(item.value)}" if item.value is not None else ""
                    out.append(f"  - field `{item.target.id}: {ast.unparse(item.annotation)}"
                               f"{default}`")
                elif isinstance(item, ast.FunctionDef) and (
                        not item.name.startswith("_") or item.name == "__init__"):
                    deco = "".join(f"@{ast.unparse(d)} " for d in item.decorator_list)
                    out.append(f"  - method `{deco}{_sig(item)}`")
                    out += _quote(_doc(item), "    ") if _doc(item) else []
    return "\n".join(out).rstrip() + "\n"


def importers_of(ref: str, built: list[str]) -> dict[str, set[str]]:
    """Names other files at ref import from each built module."""
    mods = {module_name(p) for p in built}
    files = [f for f in git("ls-tree", "-r", "--name-only", ref, "src", "tests").split()
             if f.endswith(".py") and f not in built]
    found: dict[str, set[str]] = {}
    for f in files:
        try:
            tree = ast.parse(show(ref, f))
        except SyntaxError:
            continue
        for n in ast.walk(tree):
            if isinstance(n, ast.ImportFrom) and n.module in mods:
                found.setdefault(n.module, set()).update(a.name for a in n.names)
    return found


def api_section(n: str) -> str:
    cfg = LESSONS[n]
    imp = importers_of(cfg["base"], cfg["build"])
    parts = [api_for(cfg["base"], p, imp) for p in cfg["build"]]
    return MARK_START + "\n\n## Public API\n\n" + "\n".join(parts) + "\n" + MARK_END


def refresh_spec(n: str) -> None:
    spec = ROOT / MDIR / LESSONS[n]["dir"] / "SPEC.md"
    text = spec.read_text()
    new = api_section(n)
    if MARK_START in text:
        text = re.sub(re.escape(MARK_START) + r".*?" + re.escape(MARK_END), lambda _: new,
                      text, flags=re.S)
    else:
        text = text.rstrip() + "\n\n" + new + "\n"
    spec.write_text(text)
    print(f"refreshed {spec.relative_to(ROOT)}")


# -- start branches -------------------------------------------------------------------

def empty_module(ref: str, path: str, mdir: str) -> str:
    tree = ast.parse(show(ref, path))
    doc = ast.get_docstring(tree, clean=False) or ""
    note = (f"\n\nYou build this module in this milestone. Its public API, behaviour and exact "
            f"messages\nare in {MDIR}/{mdir}/SPEC.md; the tests are the answer key.\n")
    return f'"""{doc.rstrip()}{note}"""\n'


def build(n: str) -> None:
    cfg = LESSONS[n]
    branch = f"{PREFIX}-{n}-start"
    with tempfile.TemporaryDirectory() as tmp:
        wt = Path(tmp) / "wt"
        git("worktree", "add", "-q", "--detach", str(wt), cfg["base"])
        try:
            # the Claude Code setup and the plan-phase docs always come from main's working tree
            for item in CFG.get("copy_from_main", []):
                src, dst = ROOT / item, wt / item
                if src.is_dir():
                    shutil.rmtree(dst, ignore_errors=True)
                    shutil.copytree(src, dst)
                elif src.exists():
                    dst.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy2(src, dst)
            mdir = wt / MDIR / cfg["dir"]
            mdir.mkdir(parents=True, exist_ok=True)
            for name in ("SPEC.md", "PROMPTS.md"):
                src = ROOT / MDIR / cfg["dir"] / name
                if src.exists():
                    (mdir / name).write_text(src.read_text())
            for p in cfg["build"]:
                (wt / p).write_text(empty_module(cfg["base"], p, cfg["dir"]))
            git("add", "-A", cwd=wt)
            names = ", ".join(Path(p).name for p in cfg["build"])
            git("commit", "-q", "-m",
                f"Milestone {n} start: build {names} from SPEC.md\n\n"
                f"Reference code for milestone {n} with its built modules reduced to their\n"
                f"module docstrings. Generated by kit/make_kit.py.", cwd=wt)
            sha = git("rev-parse", "HEAD", cwd=wt).strip()
        finally:
            git("worktree", "remove", "--force", str(wt))
    git("branch", "-f", branch, sha)
    print(f"{branch} -> {sha[:7]}")


def export(n: str, dest: str) -> None:
    """Write the whole tree of milestone-NN-start into dest, without git history."""
    out = Path(dest)
    out.mkdir(parents=True, exist_ok=True)
    if any(out.iterdir()):
        raise SystemExit(f"{out} is not empty")
    archive = subprocess.run(["git", "archive", f"{PREFIX}-{n}-start"], cwd=ROOT, check=True,
                             capture_output=True).stdout
    subprocess.run(["tar", "-x", "-C", str(out)], input=archive, check=True)
    print(f"exported {PREFIX}-{n}-start to {out}")


if __name__ == "__main__":
    cmd, which = sys.argv[1], sys.argv[2]
    if cmd == "export":
        export(which, sys.argv[3])
        raise SystemExit
    targets = list(LESSONS) if which == "all" else [which]
    for t in targets:
        {"api": lambda x: print(api_section(x)), "spec": refresh_spec, "build": build}[cmd](t)
